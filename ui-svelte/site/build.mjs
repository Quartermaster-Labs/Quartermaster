const fmtSize = (n) => `${(n / 1024 / 1024).toFixed(0)} MB`;

// The installer asset name carries the version, so there is no stable
// /releases/latest/download/<name> URL to hard-code, so we resolve the real one at
// build time. The Pages workflow also runs on `release: published`, so the
// button is rebuilt when a release lands. No gh, no releases, or a network
// failure all degrade to the releases page rather than failing the build.
function latestRelease() {
  try {
    const list = JSON.parse(
      execFileSync("gh", ["release", "list", "--limit", "20", "--json", "tagName,isDraft,isPrerelease"], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }),
    );
    // Prereleases are skipped, not just drafts. A prerelease exists to go to one
    // tester by hand; the updater already ignores it (/releases/latest omits it,
    // and internal/update's semverRe will not parse a suffixed tag), and the
    // download button is the last path by which a test build could still reach
    // an ordinary visitor. The isPrerelease field below stays wired so the label
    // still works if that policy is ever relaxed.
    const rel = list.find((r) => !r.isDraft && !r.isPrerelease && /^v\d+\.\d+/.test(r.tagName));
    if (!rel) return null;
    const view = JSON.parse(
      execFileSync("gh", ["release", "view", rel.tagName, "--json", "tagName,publishedAt,assets"], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }),
    );
    // Every asset name ends in the version, so all of these are prefix matches
    // rather than equality: hard-coding a full name would mean editing this file
    // on every release. The prefix has to include the platform, because the
    // release also carries quartermaster-windows-amd64.exe (the raw server
    // binary the updater fetches), and a "Download" button pointing at that
    // would hand a first-time visitor the one artifact with no wizard behind it.
    const asset = (prefix) => {
      const a = view.assets.find((x) => x.name.startsWith(prefix));
      return a ? { url: a.url, size: a.size, name: a.name } : null;
    };
    const exe = asset("quartermaster-setup-windows-amd64-");
    if (!exe) return null;
    // One wizard per platform for the hero button. Linux resolves to amd64:
    // arm64 exists in the same release, but nothing in a browser reliably
    // reports the CPU (userAgentData's `architecture` is Chromium-only and
    // async), and guessing wrong hands someone a binary that will not exec.
    // The note under the button links every asset for that case.
    return {
      tag: view.tagName,
      url: exe.url,
      size: exe.size,
      prerelease: rel.isPrerelease,
      perOS: {
        windows: exe,
        linux: asset("quartermaster-setup-linux-amd64-"),
        mac: asset("quartermaster-setup-darwin-arm64-"),
      },
    };
  } catch {
    return null;
  }
}

